#!/bin/sh
# Model servers of a cluster worker node (change model-placements, decision 44): one Ollama per GPU, each
# sees only its own card; the model files are shared. A node without a GPU runs one Ollama only when asked
# (YORATH_NODE_MODEL=on at join). Called by join.sh and by install.sh on a node that is already joined;
# run as root from the installation directory.
#
# Writes installer/compose.models.yaml (generated, not in the repository) and the node's cards into
# installer/.env.local: the node service reports them to the main node, which keeps one model server per card.
# Which model stands on which server is decided on the main node: yorath model pull <model> --node <node>.

set -eu

env_local="installer/.env.local"
out="installer/compose.models.yaml"

say() { printf '\033[1;34m[yorath]\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m[yorath] error:\033[0m %s\n' "$*" >&2; exit 1; }
set_local() {
  touch "$env_local"; chmod 600 "$env_local"
  grep -v "^$1=" "$env_local" > "$env_local.tmp" || true
  echo "$1=$2" >> "$env_local.tmp"; mv "$env_local.tmp" "$env_local"; chmod 600 "$env_local"
}
get_local() { [ -f "$env_local" ] && sed -n "s/^$1=//p" "$env_local" | tail -1 || true; }

[ -f distribution.yaml ] || die "run from the installation directory"

# --- cards: provider images often ship nvidia-smi without a GPU, so ask it for the list ---------------
gpu_count=0; gpu_name=""; gpu_vram=""
if command -v nvidia-smi >/dev/null 2>&1 && nvidia-smi -L >/dev/null 2>&1; then
  gpu_count="$(nvidia-smi -L 2>/dev/null | grep -c '^GPU ' || true)"
  gpu_name="$(nvidia-smi --query-gpu=name --format=csv,noheader 2>/dev/null | head -1 || true)"
  gpu_mib="$(nvidia-smi --query-gpu=memory.total --format=csv,noheader,nounits 2>/dev/null | head -1 | tr -d ' ' || true)"
  case "$gpu_mib" in ''|*[!0-9]*) gpu_mib="" ;; esac
  [ -n "$gpu_mib" ] && gpu_vram="$(( gpu_mib / 1024 ))"
fi
case "$gpu_count" in ''|*[!0-9]*) gpu_count=0 ;; esac

# the choice made at join is kept on later runs
model="${YORATH_NODE_MODEL:-$(get_local YORATH_NODE_MODEL)}"
[ "$model" = "on" ] || model="off"

# --- GPU: containers get the cards through nvidia-container-toolkit (same steps as install.sh) --------
if [ "$gpu_count" -gt 0 ]; then
  if ! command -v nvidia-ctk >/dev/null 2>&1; then
    say "installing nvidia-container-toolkit"
    export DEBIAN_FRONTEND=noninteractive
    # provider images hold the NVIDIA packages: unhold only the toolkit, leave the driver alone
    apt-mark unhold nvidia-container-toolkit nvidia-container-toolkit-base libnvidia-container-tools libnvidia-container1 >/dev/null 2>&1 || true
    if ! apt-get -o DPkg::Lock::Timeout=900 install -y -qq nvidia-container-toolkit >/dev/null 2>&1; then
      install -m 0755 -d /etc/apt/keyrings
      curl -fsSL https://nvidia.github.io/libnvidia-container/gpgkey | gpg --dearmor -o /etc/apt/keyrings/nvidia-container-toolkit.gpg --yes
      curl -fsSL https://nvidia.github.io/libnvidia-container/stable/deb/nvidia-container-toolkit.list \
        | sed 's#deb https://#deb [signed-by=/etc/apt/keyrings/nvidia-container-toolkit.gpg] https://#' \
        > /etc/apt/sources.list.d/nvidia-container-toolkit.list
      apt-get -o DPkg::Lock::Timeout=900 update -qq
      apt-get -o DPkg::Lock::Timeout=900 install -y -qq nvidia-container-toolkit >/dev/null
    fi
  fi
  if ! docker info 2>/dev/null | grep -q 'Runtimes:.*nvidia'; then
    nvidia-ctk runtime configure --runtime=docker >/dev/null 2>&1
    systemctl restart docker
  fi
fi

# --- Compose: one service per model server ------------------------------------------------------------
service() {  # name, device id or "" for a server without a GPU
  cat <<YAML
  ollama-$1:
    image: \${YORATH_IMAGE_OLLAMA}
    environment:
      OLLAMA_KEEP_ALIVE: \${YORATH_OLLAMA_KEEP_ALIVE}
      OLLAMA_MAX_LOADED_MODELS: "1"
      OLLAMA_CONTEXT_LENGTH: \${YORATH_OLLAMA_CONTEXT_LENGTH}
      LLAMA_ARG_CACHE_RAM: \${YORATH_OLLAMA_CACHE_RAM_MIB:-0}
    volumes:
      - ollama-data:/root/.ollama
    mem_limit: \${YORATH_OLLAMA_MEM_LIMIT}
    restart: unless-stopped
YAML
  [ -z "$2" ] || cat <<YAML
    deploy:
      resources:
        reservations:
          devices:
            - driver: nvidia
              device_ids: ["$2"]
              capabilities: [gpu]
YAML
}

{
  echo "# Generated by installer/node-models.sh: model servers of this node. Do not edit by hand."
  echo "name: yorath"
  if [ "$gpu_count" -gt 0 ] || [ "$model" = "on" ]; then
    echo "services:"
    if [ "$gpu_count" -gt 0 ]; then
      i=0
      while [ "$i" -lt "$gpu_count" ]; do service "gpu$i" "$i"; i=$((i + 1)); done
    else
      service cpu ""
    fi
    echo "volumes:"
    echo "  ollama-data:"
  else
    echo "services: {}"
  fi
} > "$out.tmp"
mv "$out.tmp" "$out"

set_local YORATH_NODE_GPU_COUNT "$gpu_count"
set_local YORATH_NODE_GPU_NAME "\"$gpu_name\""
set_local YORATH_NODE_GPU_VRAM_GB "$gpu_vram"
set_local YORATH_NODE_MODEL "$model"
set_local YORATH_COMPOSE_FILES '"-f installer/compose.worker.yaml -f installer/compose.models.yaml"'

if [ "$gpu_count" -gt 0 ]; then
  say "model servers: $gpu_count (one per card, $gpu_name ${gpu_vram:-?} GB)"
elif [ "$model" = "on" ]; then
  say "model server: one, without a GPU"
else
  say "no model server on this node: no GPU (YORATH_NODE_MODEL=on runs one on the CPU)"
fi
