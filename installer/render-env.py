#!/usr/bin/env python3
"""Generate installer/.env from distribution.yaml (single source of versions, decision 22).

Usage: python3 installer/render-env.py [--manifest distribution.yaml] [--out installer/.env]
No dependencies except PyYAML (present in the Ubuntu system Python and in the core uv environment).
"""

import argparse
import os
import subprocess
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def git_sha() -> str:
    try:
        return subprocess.check_output(
            ["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"],
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
    except Exception:  # noqa: BLE001
        return "unknown"


def host_ram_gb() -> int | None:
    """Node RAM from /proc/meminfo (Linux); without it, None, and the lower limit applies."""
    try:
        for line in Path("/proc/meminfo").read_text(encoding="utf-8").splitlines():
            if line.startswith("MemTotal:"):
                return max(1, round(int(line.split()[1]) / 1024 / 1024))
    except OSError:
        return None
    return None


def ollama_limit(manifest: dict, ram_gb: int | None) -> str:
    """Ollama container limit: node RAM minus a reserve, but not below ollama.mem_limit."""
    floor = int(str(manifest["ollama"]["mem_limit"]).lower().rstrip("gb"))
    reserve = int(manifest["models"].get("memory", {}).get("reserve_gb", 1))
    return f"{max(floor, ram_gb - reserve) if ram_gb else floor}g"


def read_env(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in text.splitlines():
        key, sep, value = line.strip().partition("=")
        if sep and key and not key.startswith("#"):
            out[key] = value.strip().strip('"')
    return out


def tls_env(env: dict[str, str]) -> dict[str, str]:
    """TLS mode for the Caddyfile (change model-endpoint): site address, tls directive, global options.

    YORATH_TLS=off: HTTP only, explicit only; YORATH_DOMAIN: Let's Encrypt (HTTP-01);
    YORATH_TLS_CERT/YORATH_TLS_KEY: own files (corporate CA, kept in installer/tls);
    otherwise the Caddy internal CA on YORATH_HOSTNAME or the node IP (YORATH_PUBLIC_IP).
    """
    if env.get("YORATH_TLS", "").lower() == "off":
        return {"YORATH_TLS_MODE": "off", "YORATH_SITE": ":80", "YORATH_TLS_DIRECTIVE": "",
                "YORATH_CADDY_EMAIL": "", "YORATH_CADDY_SNI": "", "YORATH_COOKIE_SECURE": "false",
                "YORATH_CA_FILE": "none"}  # fmt: skip
    domain, host, ip = (env.get(k, "").strip() for k in ("YORATH_DOMAIN", "YORATH_HOSTNAME", "YORATH_PUBLIC_IP"))
    email = env.get("YORATH_ACME_EMAIL", "").strip()
    if env.get("YORATH_TLS_CERT") and env.get("YORATH_TLS_KEY"):
        site = domain or host or ip or "localhost"
        mode, directive = "files", "tls /certs/cert.pem /certs/key.pem"
    elif domain:
        mode, site, directive = "acme", domain, ""
    else:
        mode, site, directive = "internal", host or ip or "localhost", "tls internal"
    # An SSH tunnel (ssh -L 8443:localhost:443) arrives with Host and SNI localhost: the internal CA issues
    # a certificate for that name too (issue #2); Let's Encrypt and own files are not issued for localhost
    addresses = f"{site}, localhost" if mode == "internal" and site != "localhost" else site
    return {
        "YORATH_TLS_MODE": mode,
        "YORATH_SITE": addresses,
        "YORATH_TLS_DIRECTIVE": directive,
        "YORATH_CADDY_EMAIL": f"email {email}" if email and mode == "acme" else "",
        "YORATH_CADDY_SNI": f"default_sni {ip}" if ip and site == ip else "",  # client by IP without SNI
        "YORATH_COOKIE_SECURE": "true",
        "YORATH_CA_FILE": "root.crt" if mode == "internal" else "none",  # served at /yorath-root-ca.crt
    }


def render(manifest: dict) -> str:
    d, img, ol = manifest["distribution"], manifest["images"], manifest["ollama"]
    mem_limit = ollama_limit(manifest, host_ram_gb())
    lines = [
        "# Generated by installer/render-env.py from distribution.yaml; do not edit by hand.",
        f"YORATH_VERSION={d['version']}",
        f"YORATH_SCHEMA_VERSION={d['schema_version']}",
        f"YORATH_BUILD_SHA={git_sha()}",
        f"YORATH_IMAGE_POSTGRES={img['postgres']}",
        f"YORATH_IMAGE_OLLAMA={img['ollama']}",
        f"YORATH_IMAGE_PYTHON={img['python']}",
        f"YORATH_IMAGE_NODE={img['node']}",
        f"YORATH_IMAGE_CADDY={img['caddy']}",
        f"YORATH_IMAGE_SQUID={img['squid']}",
        f"YORATH_IMAGE_UBUNTU={img['ubuntu']}",
        f"YORATH_SQUID_VERSION={manifest['egress']['squid']}",
        f"YORATH_CODEX_VERSION={manifest['runtimes']['codex_cli']}",
        f"YORATH_OLLAMA_MEM_LIMIT={mem_limit}",
        f"YORATH_OLLAMA_KEEP_ALIVE={ol['keep_alive']}",
        f"YORATH_OLLAMA_MAX_LOADED_MODELS={ol['max_loaded_models']}",
        f"YORATH_OLLAMA_CONTEXT_LENGTH={ol['context_length']}",
        f"YORATH_MODEL_DEFAULT_CPU={manifest['models']['default_cpu']}",
        f"YORATH_MODEL_DEFAULT_GPU={manifest['models']['default_gpu']}",
        f"YORATH_MODEL_EMBEDDINGS={manifest['models']['embeddings']}",
    ]
    local = ROOT / "installer" / ".env.local"
    if local.is_file():
        text = local.read_text(encoding="utf-8")
        if "YORATH_SECRET_KEY=" not in text:
            # Fernet key for the secrets store: on a VPS install.sh writes it, with make up it is set here
            import base64
            import os

            text = text.rstrip("\n") + "\nYORATH_SECRET_KEY=" + base64.urlsafe_b64encode(os.urandom(32)).decode() + "\n"
            local.write_text(text, encoding="utf-8")
        if "YORATH_SANDBOX_TOKEN=" not in text:
            import secrets

            sandbox_dir = ROOT / "installer" / ".sandbox"
            sandbox_dir.mkdir(exist_ok=True)
            text = (
                text.rstrip("\n")
                + f"\nYORATH_SANDBOX_TOKEN={secrets.token_urlsafe(32)}\nYORATH_SANDBOX_DIR={sandbox_dir}\n"
            )
            local.write_text(text, encoding="utf-8")
        if "YORATH_NODE_TOKEN=" not in text:
            import secrets

            # node-agent node service (change connected-agents): token for the core node API
            text = text.rstrip("\n") + f"\nYORATH_NODE_TOKEN={secrets.token_urlsafe(32)}\n"
            local.write_text(text, encoding="utf-8")
        lines += ["", "# TLS mode (tls_env)"]
        lines += [f'{k}="{v}"' for k, v in tls_env(read_env(text)).items()]
        lines += ["", "# from .env.local", text.strip()]
    return "\n".join(lines) + "\n"


def write_private(path: Path, text: str) -> None:
    """The .env gets .env.local: database password, secrets store key, sandbox token,
    so the file is root-only (0600). Otherwise any non-root agent on the server could read them."""
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    os.fchmod(fd, 0o600)  # the file may be left over from older versions with 0644
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(text)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", type=Path, default=ROOT / "distribution.yaml")
    ap.add_argument("--out", type=Path, default=ROOT / "installer" / ".env")
    a = ap.parse_args()
    manifest = yaml.safe_load(a.manifest.read_text(encoding="utf-8"))
    write_private(a.out, render(manifest))
    print(f"{a.out.relative_to(ROOT)}: {manifest['distribution']['name']} {manifest['distribution']['version']}")


if __name__ == "__main__":
    main()
