"""Core settings from environment variables with the ``YORATH_`` prefix.

Defaults match Compose.
"""

from functools import lru_cache
from pathlib import Path

from pydantic import field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


def _find_manifest() -> Path:
    """Finds distribution.yaml up from the package (dev run in the monorepo) or in /app (image)."""
    here = Path(__file__).resolve()
    for parent in [*here.parents, Path("/app")]:
        candidate = parent / "distribution.yaml"
        if candidate.is_file():
            return candidate
    return Path("distribution.yaml")


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_prefix="YORATH_", env_file=".env", extra="ignore")

    database_url: str = "postgresql+asyncpg://yorath:yorath@db:5432/yorath"
    ollama_url: str = "http://ollama:11434"
    manifest_path: Path = _find_manifest()
    agents_dir: Path = _find_manifest().parent / "agents"
    build_sha: str = "dev"
    health_timeout_seconds: float = 3.0
    session_ttl_hours: int = 168
    setup_code: str | None = None  # one-time wizard code, generated by install.sh
    secret_key: str | None = None  # Fernet key for the secret store
    node_name: str = "local"
    gpu_name: str | None = None  # filled in by the installer from nvidia-smi
    gpu_vram_gb: int | None = None
    gpu_count: int | None = None  # nvidia-smi -L; Community limit after MVP: max(1, GPU) per node
    node_ram_gb: int | None = None  # node memory, when /proc/meminfo does not reflect it
    openrouter_url: str = "https://openrouter.ai/api/v1"
    tavily_url: str = "https://api.tavily.com"
    documents_dir: Path = (
        _find_manifest().parent / "data" / "documents"
    )  # in Compose, the /data/documents volume
    max_upload_mb: int = 50
    github_api_url: str = "https://api.github.com"
    sandbox_dir: Path = Path("/var/lib/yorath/sandbox")  # same path in core, runner and sandbox
    sandbox_url: str = "http://sandbox-runner:8090"
    sandbox_token: str = ""
    node_token: str = ""  # node service node-agent (connected-agents); empty closes the node API
    cluster_dir: Path = Path("/cluster")  # WireGuard peers for yorath node sync (cluster-nodes)
    sandbox_gateway_url: str = "http://core:8000"  # through the egress proxy, only /gateway/v1
    egress_log: str = "/data/egress/access.log"
    host_report_dir: Path = Path(
        "/host-report"
    )  # yorath scan report from the host: agents outside Yorath
    egress_node_log: Path = Path("/data/egress-node/access.log")  # node proxy log (node-egress)
    # The boundary is the gVisor container: in workspace-write Codex 0.166 under gVisor does not
    # write files via apply_patch, and under runc its sandbox does not work at all (measured on
    # a VPS).
    codex_sandbox: str = "danger-full-access"

    @field_validator(
        "setup_code", "secret_key", "gpu_name", "gpu_vram_gb", "gpu_count", mode="before"
    )
    @classmethod
    def _empty_is_none(cls, v: object) -> object:
        return None if v == "" else v  # Compose passes empty strings for unset variables

    cookie_secure: bool = False  # turned on together with TLS in the installer


@lru_cache
def get_settings() -> Settings:
    return Settings()
